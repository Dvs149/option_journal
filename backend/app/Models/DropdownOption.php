    /**
     * Seed defaults for a specific user if empty
     */
    public static function seedDefaultsForUser(int $userId): void
    {
        $defaults = self::getDefaultOptions();
        foreach ($defaults as $opt) {
            self::firstOrCreate(
                [
                    'user_id' => $userId,
                    'module_key' => $opt['module_key'],
                    'dropdown_key' => $opt['dropdown_key'],
                    'option_value' => $opt['option_value'],
                ],
                [
                    'dropdown_label' => $opt['dropdown_label'],
                    'option_label' => $opt['option_label'],
                    'is_active' => true,
                    'sort_order' => $opt['sort_order'],
                    'is_system' => true,
                    'color' => $opt['color'] ?? 'blue',
                ]
            );
        }
    }
